"""
configs/register_datasets.py
Registers WheelPose datasets into Detectron2's DatasetCatalog.
Call register_all() once before any training or evaluation script.
"""

import os
from detectron2.data.datasets import register_coco_instances
from detectron2.data import MetadataCatalog

# ── COCO 17-keypoint standard (same schema WheelPose uses) ───────────────────
KEYPOINT_NAMES = [
    "nose",
    "left_eye",  "right_eye",
    "left_ear",  "right_ear",
    "left_shoulder", "right_shoulder",
    "left_elbow",    "right_elbow",
    "left_wrist",    "right_wrist",
    "left_hip",      "right_hip",
    "left_knee",     "right_knee",
    "left_ankle",    "right_ankle",
]

KEYPOINT_FLIP_MAP = [
    ("left_eye",      "right_eye"),
    ("left_ear",      "right_ear"),
    ("left_shoulder", "right_shoulder"),
    ("left_elbow",    "right_elbow"),
    ("left_wrist",    "right_wrist"),
    ("left_hip",      "right_hip"),
    ("left_knee",     "right_knee"),
    ("left_ankle",    "right_ankle"),
]

# ── Paths — edit ROOT if your data lives elsewhere ───────────────────────────
ROOT = os.path.join(os.path.dirname(__file__), "..", "data")

DATASETS = {
    # ── Real-world test set (2464 images, from WheelPose GitHub) ─────────────
    # Download from: https://github.com/hilab-open-source/wheelpose
    # Place images in  data/real_world/images/
    # Place annotation in data/real_world/annotations.json
    "wheelpose_test": {
        "ann":  os.path.join(ROOT, "real_world", "annotations.json"),
        "imgs": os.path.join(ROOT, "real_world", "images"),
    },

    # ── Synthetic training set ────────────────────────────────────────────────
    # [PLACEHOLDER] Generated by Stage 1 (Unity WheelPose-Opt pipeline).
    # Expected: 70,000 frames at 1280x720, COCO-format annotations.
    # When ready: copy/symlink images → data/synthetic/images/
    #             copy annotation  → data/synthetic/annotations.json
    "wheelpose_train": {
        "ann":  os.path.join(ROOT, "synthetic", "annotations.json"),
        "imgs": os.path.join(ROOT, "synthetic", "images"),
    },
}


def register_all():
    for name, paths in DATASETS.items():
        if os.path.exists(paths["ann"]) and os.path.exists(paths["imgs"]):
            register_coco_instances(name, {}, paths["ann"], paths["imgs"])
            meta = MetadataCatalog.get(name)
            meta.keypoint_names     = KEYPOINT_NAMES
            meta.keypoint_flip_map  = KEYPOINT_FLIP_MAP
            meta.thing_classes      = ["person"]
            print(f"[register_datasets] Registered '{name}'")
        else:
            print(
                f"[register_datasets] WARNING: '{name}' skipped — "
                f"data not found at:\n"
                f"  annotations : {paths['ann']}\n"
                f"  images      : {paths['imgs']}"
            )


if __name__ == "__main__":
    register_all()
